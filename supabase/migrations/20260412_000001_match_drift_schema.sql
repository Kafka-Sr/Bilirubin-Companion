-- hospitals -------------------------------------------------------------------
-- Any logged-in user may read all hospitals.
-- (Needed for: showing own hospital name, and looking up transfer codes.)
-- Creating / editing hospitals is done via the Supabase dashboard or a
-- service-role migration script — no user-facing policy needed.
create policy "hospitals: authenticated read"
  on public.hospitals for select
  to authenticated
  using (true);

-- user_profiles ---------------------------------------------------------------
-- A user can always read their own profile.
create policy "user_profiles: read own"
  on public.user_profiles for select
  to authenticated
  using (user_id = auth.uid());

-- Admins can read every profile in their hospital (staff management screen).
create policy "user_profiles: admin reads same hospital"
  on public.user_profiles for select
  to authenticated
  using (
    hospital_id = public.my_hospital_id()
    and public.my_role() = 'admin'
  );

-- INSERT / UPDATE / DELETE are handled exclusively by Edge Functions that run
-- under the service-role key (create-staff, etc.).  No user-level policies.

-- babies ----------------------------------------------------------------------
create policy "babies: staff read"
  on public.babies for select
  to authenticated
  using (hospital_id = public.my_hospital_id());

create policy "babies: staff insert"
  on public.babies for insert
  to authenticated
  with check (hospital_id = public.my_hospital_id());

create policy "babies: staff update"
  on public.babies for update
  to authenticated
  using     (hospital_id = public.my_hospital_id())
  with check(hospital_id = public.my_hospital_id());

create policy "babies: staff delete"
  on public.babies for delete
  to authenticated
  using (hospital_id = public.my_hospital_id());

-- Parents can read the specific baby they are linked to.
create policy "babies: parent read linked"
  on public.babies for select
  to authenticated
  using (
    exists (
      select 1 from public.parent_baby_access pba
      where pba.parent_user_id = auth.uid()
        and pba.hospital_id    = babies.hospital_id
        and pba.baby_local_id  = babies.local_id
    )
  );

-- measurements ----------------------------------------------------------------
create policy "measurements: staff read"
  on public.measurements for select
  to authenticated
  using (hospital_id = public.my_hospital_id());

create policy "measurements: staff insert"
  on public.measurements for insert
  to authenticated
  with check (hospital_id = public.my_hospital_id());

-- Parents can read measurements for their linked baby.
create policy "measurements: parent read linked"
  on public.measurements for select
  to authenticated
  using (
    exists (
      select 1 from public.parent_baby_access pba
      where pba.parent_user_id = auth.uid()
        and pba.hospital_id    = measurements.hospital_id
        and pba.baby_local_id  = measurements.baby_local_id
    )
  );

-- transfer_requests -----------------------------------------------------------
create policy "transfers: admin read"
  on public.transfer_requests for select
  to authenticated
  using (
    public.my_role() = 'admin'
    and (from_hospital_id = public.my_hospital_id()
         or to_hospital_id  = public.my_hospital_id())
  );

create policy "transfers: admin insert"
  on public.transfer_requests for insert
  to authenticated
  with check (
    public.my_role() = 'admin'
    and from_hospital_id = public.my_hospital_id()
  );

create policy "transfers: admin update"
  on public.transfer_requests for update
  to authenticated
  using (
    public.my_role() = 'admin'
    and (from_hospital_id = public.my_hospital_id()
         or to_hospital_id  = public.my_hospital_id())
  );

-- parent_baby_access ----------------------------------------------------------
create policy "parent_access: read own"
  on public.parent_baby_access for select
  to authenticated
  using (parent_user_id = auth.uid());

create policy "parent_access: admin read"
  on public.parent_baby_access for select
  to authenticated
  using (
    hospital_id = public.my_hospital_id()
    and public.my_role() = 'admin'
  );

create policy "parent_access: admin insert"
  on public.parent_baby_access for insert
  to authenticated
  with check (
    hospital_id = public.my_hospital_id()
    and public.my_role() = 'admin'
  );

create policy "parent_access: admin delete"
  on public.parent_baby_access for delete
  to authenticated
  using (
    hospital_id = public.my_hospital_id()
    and public.my_role() = 'admin'
  );

