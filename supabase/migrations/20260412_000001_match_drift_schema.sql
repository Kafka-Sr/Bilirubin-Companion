-- ── Core tables ──────────────────────────────────────────────────────────────

-- Every hospital that uses the system gets one row here.
-- The 'code' field is the short identifier staff type when initiating transfers.
create table public.hospitals (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  code       text not null unique,   -- e.g. 'RSU-01'
  created_at timestamptz not null default now()
);

-- One profile per auth.users entry.
-- hospital_id is NULL for parent accounts (they belong to no hospital).
create table public.user_profiles (
  user_id     uuid primary key references auth.users(id) on delete cascade,
  hospital_id uuid references public.hospitals(id) on delete set null,
  role        text not null check (role in ('admin', 'staff', 'nurse', 'parent')),
  email       text not null,
  created_at  timestamptz not null default now()
);

-- Composite PK (hospital_id, local_id) matches the upsert conflict target
-- the Flutter app uses.  local_id is the SQLite rowid on the device.
create table public.babies (
  hospital_id   uuid        not null references public.hospitals(id) on delete cascade,
  local_id      integer     not null,
  name          text        not null,
  date_of_birth timestamptz not null,
  weight_kg     double precision not null,
  is_archived   boolean     not null default false,
  created_at    timestamptz not null,
  updated_at    timestamptz not null,
  primary key (hospital_id, local_id)
);

-- baby_local_id is nullable so the gun can push a measurement directly to
-- Supabase without knowing which baby is selected.  The app fills it in via
-- a subsequent upsert (ON CONFLICT DO UPDATE) when it processes the same
-- measurement through the normal flow.
--
-- Gun must use:  INSERT ... ON CONFLICT (measurement_id) DO NOTHING
-- App uses:      INSERT ... ON CONFLICT (measurement_id) DO UPDATE SET ...
-- This guarantees the app's fuller record (with baby_local_id) always wins.
create table public.measurements (
  measurement_id  text        primary key,   -- UUID generated by the gun
  hospital_id     uuid        not null references public.hospitals(id) on delete cascade,
  baby_local_id   integer,                   -- null = gun-direct push, filled in by app
  captured_at     timestamptz not null,
  received_at     timestamptz,               -- absent on gun-direct push
  age_hours       double precision,          -- absent on gun-direct push
  bilirubin_mg_dl double precision not null,
  has_image       boolean not null default false,
  device_id       text,
  model_version   text,
  created_at      timestamptz not null default now()
  -- No FK to babies: measurements outlive baby records and baby_local_id is
  -- nullable.  Integrity is enforced at the application level.
);

-- Pending transfers between hospitals.
-- from_hospital initiates; to_hospital accepts or rejects.
create table public.transfer_requests (
  id               uuid        primary key default gen_random_uuid(),
  baby_name        text        not null,
  from_hospital_id uuid        not null references public.hospitals(id),
  to_hospital_id   uuid        not null references public.hospitals(id),
  status           text        not null default 'pending'
                     check (status in ('pending','accepted','rejected','cancelled')),
  initiated_by     uuid        not null references auth.users(id),
  resolved_by      uuid        references auth.users(id),
  resolved_at      timestamptz,
  initiated_at     timestamptz not null default now()
);

-- Grants a parent account read-only visibility of one baby's data.
-- Cascades on baby deletion so stale access rows are cleaned up automatically.
create table public.parent_baby_access (
  parent_user_id uuid    not null references auth.users(id) on delete cascade,
  hospital_id    uuid    not null,
  baby_local_id  integer not null,
  granted_by     uuid    not null references auth.users(id),
  granted_at     timestamptz not null default now(),
  primary key (parent_user_id, hospital_id, baby_local_id),
  foreign key (hospital_id, baby_local_id)
    references public.babies(hospital_id, local_id) on delete cascade
);

-- ── Indexes ───────────────────────────────────────────────────────────────────

create index on public.user_profiles     (hospital_id);
create index on public.measurements      (hospital_id, baby_local_id);
create index on public.measurements      (captured_at desc);
create index on public.measurements      (device_id);
create index on public.transfer_requests (from_hospital_id);
create index on public.transfer_requests (to_hospital_id);
create index on public.transfer_requests (status);
create index on public.parent_baby_access (hospital_id, baby_local_id);

-- ── Helper functions (used by RLS policies) ──────────────────────────────────

-- Returns the hospital_id of the currently authenticated user, or NULL.
create or replace function public.my_hospital_id()
returns uuid language sql stable security definer as $$
  select hospital_id
  from   public.user_profiles
  where  user_id = auth.uid()
$$;

-- Returns the role of the currently authenticated user, or NULL.
create or replace function public.my_role()
returns text language sql stable security definer as $$
  select role
  from   public.user_profiles
  where  user_id = auth.uid()
$$;

